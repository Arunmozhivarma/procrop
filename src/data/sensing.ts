import type { Device, EnvReading, ForecastDay, SoilMetric } from "@/types/sensing";

function buildSoil(
  moisture: number,
  ph: number,
  n: number,
  p: number,
  k: number,
  temp: number,
): SoilMetric[] {
  const mk = (
    key: string,
    label: string,
    icon: string,
    value: number,
    unit: string,
    ideal: [number, number],
    range: [number, number],
    note: string,
  ): SoilMetric => ({
    key,
    label,
    icon,
    value,
    unit,
    ideal,
    range,
    status: value < ideal[0] ? "low" : value > ideal[1] ? "high" : "optimal",
    note,
  });

  return [
    mk(
      "moisture",
      "Soil moisture",
      "water_drop",
      moisture,
      "%",
      [45, 65],
      [0, 100],
      "Volumetric water content at 20 cm depth.",
    ),
    mk(
      "ph",
      "pH",
      "science",
      ph,
      "",
      [6.0, 7.2],
      [3, 10],
      "Acidity affects nutrient availability, especially phosphorus.",
    ),
    mk(
      "n",
      "Nitrogen (N)",
      "eco",
      n,
      "kg/ha",
      [100, 160],
      [0, 250],
      "Drives vegetative growth and canopy density.",
    ),
    mk(
      "p",
      "Phosphorus (P)",
      "grain",
      p,
      "kg/ha",
      [30, 55],
      [0, 90],
      "Supports root establishment and flowering.",
    ),
    mk(
      "k",
      "Potassium (K)",
      "bolt",
      k,
      "kg/ha",
      [140, 220],
      [0, 320],
      "Improves stress tolerance and disease resistance.",
    ),
    mk(
      "temp",
      "Soil temperature",
      "device_thermostat",
      temp,
      "°C",
      [20, 28],
      [5, 45],
      "Governs microbial activity and root uptake.",
    ),
  ];
}

